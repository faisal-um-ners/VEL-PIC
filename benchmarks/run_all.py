def write_report():
    files = sorted(glob.glob(os.path.join(RESULTS, "[0-9][0-9]_*.json")))
    lines = ["# VEXPACE - Validation report", "",
             "Generated by `benchmarks/run_all.py`. Each benchmark compares VEXPACE with an analytic "
             "result, a published law or another code (WarpX).", "",
             "| # | Benchmark | Case | VEXPACE | Reference | Error | Status |",
             "|---|---|---|---|---|---|---|"]
    details = []
    npass = ntot = 0
    for f in files:
        d = json.load(open(f))
        num = d["name"].split("_")[0]
        for r in d["rows"]:
            ntot += 1
            npass += r["passed"]
            err = f"{100 * r['error']:+.2f} %" if r["reference"] != 0 else f"{r['error']:.2e}"
            lines.append(f"| {num} | {d['title']} | {r['case']} | {r['value']:.5g} | {r['reference']:.5g} | "
                         f"{err} | {'PASS' if r['passed'] else 'FAIL'} |")
        details.append(f"## {num}. {d['title']}\n")
        if d.get("notes"):
            details.append(d["notes"] + "\n")
        png = d["name"] + ".png"
        if os.path.exists(os.path.join(RESULTS, png)):
            details.append(f"![{d['title']}]({png})\n")
    lines.insert(4, f"**{npass} / {ntot} checks passed.**\n")
    with open(os.path.join(RESULTS, "VALIDATION_REPORT.md"), "w") as fh:
        fh.write("\n".join(lines) + "\n\n" + "\n".join(details))
    print(f"\nReport: {os.path.join(RESULTS, 'VALIDATION_REPORT.md')}  ({npass}/{ntot} passed)")


def main(names):
    todo = names or list(SUITE)
    for n in todo:
        t0 = time.time()
        try:
            SUITE[n]()
        except Exception:  # noqa: BLE001
            traceback.print_exc()
        print(f"   [{n}: {time.time() - t0:.0f} s]", flush=True)
    write_report()


if __name__ == "__main__":
    main(sys.argv[1:])
